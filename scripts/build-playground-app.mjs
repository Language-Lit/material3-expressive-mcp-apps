import { build } from 'esbuild'
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const result = await build({
  absWorkingDir: root,
  entryPoints: ['playground/app-main.tsx'],
  outfile: 'app.js',
  bundle: true, write: false, minify: true, format: 'iife',
  define: { 'process.env.NODE_ENV': '"production"' },
})
const js = result.outputFiles.find((file) => file.path.endsWith('.js')).text.replace(/<\/script/gi, '<\\/script')
const css = result.outputFiles.find((file) => file.path.endsWith('.css')).text.replace(/<\/style/gi, '<\\/style')
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Forecast</title><style>${css}</style></head><body><div id="root"></div><script>${js}</script></body></html>`
await mkdir(path.join(root, 'playground/generated'), { recursive: true })
await writeFile(path.join(root, 'playground/generated/app.ts'), `// Generated by scripts/build-playground-app.mjs.\nexport const html = ${JSON.stringify(html)}\n`)
console.log('Built the self-contained playground app.')

const proxy = await build({
  absWorkingDir: root, entryPoints: ['playground/proxy.ts'],
  bundle: true, write: false, minify: true, format: 'iife',
})
const proxyHtml = `<!doctype html><html><head><meta charset="utf-8"><title>MCP sandbox proxy</title><style>html,body{margin:0;width:100%;height:100%;overflow:hidden}</style></head><body><script>${proxy.outputFiles[0].text.replace(/<\/script/gi, '<\\/script')}</script></body></html>`
await writeFile(path.join(root, 'playground/generated/proxy.html'), proxyHtml)
await build({
  absWorkingDir: root, entryPoints: ['playground/proxy-server.ts'],
  outfile: 'playground/generated/proxy-server.mjs', bundle: true, platform: 'node', format: 'esm',
})
console.log('Built the sandbox proxy fixture.')
